// Two operations that start on the same line (one spans more lines) give one
// evidence entry per file and line, not one per line span.
func TestEFEvidenceDedupesOnFileAndLine(t *testing.T) {
	up := initUp + `
            migrationBuilder.AddColumn<int>(name: "A", table: "Orders", nullable: true); migrationBuilder.AddColumn<int>(
                name: "B",
                table: "Orders",
                nullable: true);`
	files := map[string]string{
		"src/Infrastructure/Infrastructure.csproj":                efProject("Microsoft.EntityFrameworkCore.SqlServer"),
		"src/Infrastructure/Migrations/20240101_Init.cs":          migration("Init", up),
		"src/Infrastructure/Migrations/20240101_Init.Designer.cs": designer("Init", "20240101_Init", "AppDbContext"),
	}
	tb := byKey(efRun(t, files).Facts, fact.KindDBTable)[efPrefix+"dbo.Orders"]
	seen := map[int]int{}
	for _, e := range tb.Evidence {
		seen[e.Line]++
	}
	line := lineOf(t, migration("Init", up), `name: "A"`)
	if seen[line] != 1 {
		t.Errorf("evidence at line %d: %d entries, want 1: %v", line, seen[line], tb.Evidence)
	}
	for l, n := range seen {
		if n > 1 {
			t.Errorf("line %d has %d evidence entries: %v", l, n, tb.Evidence)
		}
	}
}
