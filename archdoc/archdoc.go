func stackName(key string) string { return key[strings.LastIndex(key, ":")+1:] }

// stackID is <tool>:<name> of a stack:<tool>:<name> key: stacks of two
// tools can share a name (helm and kubernetes "chart").
func stackID(key string) string { return strings.TrimPrefix(key, "stack:") }

// stackOf is the stack (<tool>:<stack>) of a service or data store key,
// service:<tool>:<stack>:<name>; "" for a CI image.
func stackOf(key string) string {
	parts := strings.SplitN(key, ":", 4)
	if len(parts) == 4 && (parts[0] == "service" || parts[0] == "datastore") {
		return parts[1] + ":" + parts[2]
	}
	return ""
}

func commonPrefix(ps []string) string {
	if len(ps) < 2 {
		return ""
	}
	pre := ps[0]
	for _, p := range ps[1:] {
		for !strings.HasPrefix(p, pre) {
			pre = pre[:len(pre)-1]
		}
	}
	if i := strings.LastIndex(pre, "/"); i >= 0 {
		return pre[:i+1]
	}
	return ""
}

var mdEsc = strings.NewReplacer(`\`, `\\`, "&", "&amp;", "<", "&lt;", ">", "&gt;", "|", `\|`, "[", `\[`, "]", `\]`, "`", "\\`",
	"\r\n", " ", "\n", " ", "\r", " ", "\u2028", " ", "\u2029", " ")

// md escapes a repo string for Markdown text: raw HTML, link syntax, code
// spans and table pipes in it stay literal, and it stays on one line.
func md(s string) string { return mdEsc.Replace(s) }

// cell is md for a table cell.
func cell(s string) string { return md(s) }

var codeEsc = strings.NewReplacer("`", "'", "<", "\u2039", ">", "\u203a",
	"\r\n", " ", "\n", " ", "\r", " ", "\u2028", " ", "\u2029", " ")

// code is a code span for a repo string. It has no backtick in it, so it
// cannot end early, and no < or >, for renderers that also read HTML there.
// A backslash is literal in a code span, so a pipe stays as it is.
func code(s string) string { return "`" + codeEsc.Replace(s) + "`" }

// codeCell is code for a table cell: the table reads \| as a pipe before the
// code span does, so a pipe cannot end the cell.
func codeCell(s string) string { return strings.ReplaceAll(code(s), "|", `\|`) }

// urlPath percent-encodes a repo path for use inside a link target, keeping
// / and the characters common in paths; (, ), spaces, # and ? are encoded.
func urlPath(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= '0' && c <= '9',
			strings.IndexByte("-._~/@+=:,", c) >= 0:
			b.WriteByte(c)
		default:
			b.WriteString("%" + strings.ToUpper(strconv.FormatInt(int64(c)+256, 16)[1:]))
		}
	}
	return b.String()
}

func short(sha string) string {
	if len(sha) > 7 {
		return sha[:7]
	}
	return sha
}

func plural(n int, one, many string) string {
	if n == 1 {
		return "1 " + one
	}
	return fmt.Sprintf("%d %s", n, many)
}

func uniq(xs []string) []string {
	slices.Sort(xs)
	return slices.DeleteFunc(slices.Compact(xs), func(x string) bool { return x == "" })
}
