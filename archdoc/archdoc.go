// Package archdoc writes architecture documentation from one scan and its
// map: Markdown with arc42 sections and C4 context and container views in
// Mermaid. Every statement carries a footnote with the facts behind it and
// their file and line. Deterministic: the same scan, map and options give
// the same bytes. Sections the code cannot answer (goals, decisions,
// quality) are left blank for a person to write. See
// https://cernly.dev/how/architecture-docs/.
package archdoc

import (
	"fmt"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/cernly/cernly/fact"
	"github.com/cernly/cernly/rules"
)

// Words explain a finding rule to a reader. A caller can pass its own; with
// none, the rule id is printed.
type Words struct {
	Title, Meaning, Action string
}

type Options struct {
	Version string           // the cernly version, printed in the header
	Words   map[string]Words // per finding rule; optional
	// Labels names stacks for a reader (a declared display name); optional.
	Labels map[string]string
	// MaxEvidence is the number of places listed per fact (default 5).
	MaxEvidence int
}

type doc struct {
	b     strings.Builder
	s     *fact.Scan
	m     *rules.Map
	o     Options
	facts map[string]fact.Fact
	notes []string       // footnote bodies, in order of first use
	ids   map[string]int // fact-set key -> footnote number
}

// Build writes the Markdown document.
func Build(s *fact.Scan, m *rules.Map, o Options) []byte {
	if o.MaxEvidence == 0 {
		o.MaxEvidence = 5
	}
	d := &doc{s: s, m: m, o: o, facts: map[string]fact.Fact{}, ids: map[string]int{}}
	for _, f := range s.Facts {
		d.facts[f.Key] = f
	}
	d.header()
	d.blank("1. Introduction and goals", "What the system is for, and its most important quality goals.")
	d.blank("2. Constraints", "Technical and organisational constraints.")
	d.context()
	d.blank("4. Solution strategy", "The fundamental decisions that shape the architecture.")
	d.buildingBlocks()
	d.blank("6. Runtime view", "How the building blocks work together in the most important scenarios.")
	d.deployment()
	d.crosscutting()
	d.blank("9. Architecture decisions", "Decisions and why they were taken.")
	d.blank("10. Quality requirements", "Quality scenarios.")
	d.risks()
	d.blank("12. Glossary", "")
	d.footnotes()
	return []byte(d.b.String())
}

func (d *doc) p(format string, a ...any) { fmt.Fprintf(&d.b, format, a...) }

// cite returns a footnote reference for a set of facts; the same set gets the
// same number. Unknown keys (derived subjects such as ci_image:) are listed
// by name only.
func (d *doc) cite(keys ...string) string {
	keys = uniq(keys)
	if len(keys) == 0 {
		return ""
	}
	id := strings.Join(keys, "\x00")
	n, ok := d.ids[id]
	if !ok {
		var lines []string
		for _, k := range keys {
			f, ok := d.facts[k]
			if !ok {
				lines = append(lines, code(k)+" (derived)")
				continue
			}
			var at []string
			for i, e := range f.Evidence {
				if i == d.o.MaxEvidence {
					at = append(at, fmt.Sprintf("and %d more", len(f.Evidence)-i))
					break
				}
				at = append(at, d.place(e))
			}
			lines = append(lines, code(k)+": "+strings.Join(at, ", "))
		}
		d.notes = append(d.notes, strings.Join(lines, "; "))
		n = len(d.notes)
		d.ids[id] = n
	}
	return fmt.Sprintf("[^%d]", n)
}

// place is file:line, linked to the file at the scanned commit on hosts
// whose URLs are known.
func (d *doc) place(e fact.Evidence) string {
	at := fmt.Sprintf("%s:%d", e.Path, e.Line)
	host, _, _ := strings.Cut(d.s.Repo, "/")
	switch host {
	case "github.com":
		return fmt.Sprintf("[%s](https://%s/blob/%s/%s#L%d)", md(at), urlPath(d.s.Repo), urlPath(d.s.Commit.SHA), urlPath(e.Path), e.Line)
	case "gitlab.com":
		return fmt.Sprintf("[%s](https://%s/-/blob/%s/%s#L%d)", md(at), urlPath(d.s.Repo), urlPath(d.s.Commit.SHA), urlPath(e.Path), e.Line)
	}
	return code(at)
}

func (d *doc) header() {
	d.p("# Architecture of %s\n\n", md(d.s.Repo))
	ver := d.o.Version
	if ver == "" {
		ver = d.s.Extractor.Version
	}
	d.p("Generated by cernly %s from commit %s of %s; rules %s, catalogue %s, default branch %s. ",
		md(ver), code(short(d.s.Commit.SHA)), md(d.s.Commit.CommittedAt), md(d.m.RulesVersion), md(d.m.CatalogueVersion), code(d.m.Settings.DefaultBranch))
	d.p("Everything below is read from the repository's tracked files, without building or running it. ")
	d.p("Each statement has a footnote with the facts behind it and the file and line of each. ")
	d.p("Sections the code cannot answer are left for a person to write.\n\n")
	if x := d.m.Metrics; x != nil {
		sc, label := x.Total, "in all stacks"
		if x.Total.ProductionStacks > 0 {
			sc, label = x.Production, "in production"
		}
		d.p("**Surface %s:** %s, %s, %s, %s, %s, %s.", label,
			plural(sc.OutsideParties, "outside party", "outside parties"), plural(sc.DataStores, "data store", "data stores"),
			plural(sc.ColumnsToCheck, "column to check", "columns to check"), plural(sc.UnpinnedImages, "unpinned image", "unpinned images"),
			plural(sc.ProductionStacks, "production stack", "production stacks"), plural(sc.Routes, "route", "routes"))
		if sc.Size.Files > 0 {
			d.p(" Size, for context: %s in %s (%s)%s.", plural(sc.Size.Lines, "line", "lines"), plural(sc.Size.Files, "file", "files"), md(langs(sc.Size)), tests(sc.Size))
		}
		d.p("\n\n")
	}
}

func (d *doc) blank(title, hint string) {
	d.p("## %s\n\n", title)
	if hint != "" {
		d.p("_Not in the code: %s_\n\n", hint)
	} else {
		d.p("_Not in the code._\n\n")
	}
}

var idUnsafe = regexp.MustCompile(`[^A-Za-z0-9_]`)

// mid is a Mermaid identifier; q is a quoted Mermaid label.
func mid(prefix, s string) string { return prefix + "_" + idUnsafe.ReplaceAllString(s, "_") }

// q is a quoted Mermaid label; mermaidText escapes with Mermaid's entity form
// (#quot;), so nothing in a repo string can end the label or start markup.
func q(s string) string { return `"` + mermaidText(s) + `"` }

// mermaidPairs map what could end a label, start markup or a %%{...}%%
// directive to Mermaid's entity codes.
var mermaidPairs = []string{"#", "#35;", `"`, "#quot;", "<", "#lt;", ">", "#gt;", "&", "#amp;",
	"`", "#96;", "[", "#91;", "]", "#93;", "%", "#37;",
	"\r\n", " ", "\n", " ", "\r", " ", "\u2028", " ", "\u2029", " "}

var (
	mermaidEsc = strings.NewReplacer(mermaidPairs...)
	// After the title keyword the text is unquoted, so ; also ends it.
	mermaidTitleEsc = strings.NewReplacer(append([]string{";", "#59;"}, mermaidPairs...)...)
)

func mermaidText(s string) string { return mermaidEsc.Replace(s) }

// mermaidTitle is for unquoted text after the title keyword.
func mermaidTitle(s string) string { return mermaidTitleEsc.Replace(s) }

func (d *doc) context() {
	d.p("## 3. Context and scope\n\n")
	sys := mid("sys", d.s.Repo)
	d.p("```mermaid\nC4Context\n  title System context of %s\n", mermaidTitle(d.s.Repo))
	d.p("  System(%s, %s, %s)\n", sys, q(d.s.Repo), q(plural(d.count(fact.KindService), "service", "services")))
	for _, p := range d.m.Parties {
		d.p("  System_Ext(%s, %s, %s)\n", mid("p", p.ID), q(p.Name), q(p.Category))
	}
	for _, p := range d.m.Parties {
		d.p("  Rel(%s, %s, %s)\n", sys, mid("p", p.ID), q("uses ("+signalKinds(p)+")"))
	}
	d.p("```\n\n")
	if len(d.m.Parties) == 0 {
		d.p("No outside party is named in the code, configuration or images.\n\n")
	} else {
		d.p("Outside parties, as the provider catalogue (%s) recognises them:\n\n", d.m.CatalogueVersion)
		d.p("| Party | Category | Seen by | Services | Evidence |\n|---|---|---|---|---|\n")
		for _, p := range d.m.Parties {
			var keys []string
			for _, g := range p.Signals {
				keys = append(keys, g.Fact)
			}
			d.p("| %s | %s | %s | %s | %s |\n", cell(p.Name), cell(p.Category), cell(signalKinds(p)), cell(d.names(p.Services)), d.cite(keys...))
		}
		d.p("\n")
	}
	if len(d.m.Unknown) > 0 {
		d.p("Hosts the code points at that no catalogue entry names (%d): ", len(d.m.Unknown))
		var hs []string
		for _, u := range d.m.Unknown {
			hs = append(hs, code(u.Host)+" "+d.cite(u.From...))
		}
		d.p("%s.\n\n", strings.Join(hs, ", "))
	}
	if len(d.m.Routes) > 0 {
		d.p("Ways in, through the web servers:\n\n| Site | Match | Action | To | Evidence |\n|---|---|---|---|---|\n")
		for _, r := range d.m.Routes {
			to := r.Upstream
			if r.To != "" {
				to = d.name(r.To)
			}
			d.p("| %s | %s | %s | %s | %s |\n", cell(strings.Join(r.Sites, ", ")), cell(r.Match), cell(r.Action), cell(to), d.cite(r.From...))
		}
		d.p("\n")
	}
}

// views are the stacks the container view draws: the production stacks, or
// every stack when none is production.
func (d *doc) views() []rules.StackRole {
	var prod []rules.StackRole
	for _, st := range d.m.Stacks {
		if st.Role == rules.RoleProduction || st.Role == rules.RoleUnconfirmed {
			prod = append(prod, st)
		}
	}
	if len(prod) > 0 {
		return prod
	}
	return d.m.Stacks
}

func (d *doc) buildingBlocks() {
	d.p("## 5. Building block view\n\n")
	views := d.views()
	if len(views) == 0 {
		d.p("No deployment stack is described in the repository.\n\n")
	}
	for _, st := range views {
		name, id := stackName(st.Stack), stackID(st.Stack)
		d.p("### Stack %s (%s)\n\n", md(d.keyLabel(st.Stack)), md(string(st.Role)))
		var boxes []fact.Fact
		for _, f := range d.s.Facts {
			if (f.Kind == fact.KindService || f.Kind == fact.KindDatastore) && stackOf(f.Key) == id {
				boxes = append(boxes, f)
			}
		}
		if len(boxes) == 0 {
			// An empty System_Boundary does not parse in Mermaid.
			d.p("This stack has no services.\n\n")
			continue
		}
		d.p("```mermaid\nC4Container\n  title Containers of stack %s\n", mermaidTitle(d.keyLabel(st.Stack)))
		d.p("  System_Boundary(%s, %s) {\n", mid("b", name), q("stack "+d.keyLabel(st.Stack)))
		for _, f := range boxes {
			tech := f.Str("image")
			if l := d.link(f.Key); l != nil {
				tech = "built from " + l.Recipe[len("image_recipe:"):]
			}
			if f.Kind == fact.KindDatastore {
				d.p("    ContainerDb(%s, %s, %s)\n", mid("c", f.Key), q(f.Str("name")), q(strings.TrimSpace(f.Str("engine")+" "+f.Str("version"))))
			} else {
				note := ""
				if n := d.endpointNote(f.Key); n != "" {
					note = ", " + q(n)
				}
				d.p("    Container(%s, %s, %s%s)\n", mid("c", f.Key), q(f.Str("name")), q(tech), note)
			}
		}
		d.p("  }\n")
		ext := map[string]bool{}
		for _, p := range d.m.Parties {
			for _, sv := range p.Services {
				if stackOf(sv) == id && !ext[p.ID] {
					ext[p.ID] = true
					d.p("  System_Ext(%s, %s, %s)\n", mid("p", p.ID), q(p.Name), q(p.Category))
				}
			}
		}
		in := map[string]bool{}
		for _, f := range boxes {
			in[f.Key] = true
		}
		for _, f := range boxes {
			for _, dep := range f.Strs("depends_on") {
				for _, kind := range []string{"service", "datastore"} {
					if k := kind + ":compose:" + name + ":" + dep; in[k] {
						d.p("  Rel(%s, %s, %s)\n", mid("c", f.Key), mid("c", k), q("depends on"))
					}
				}
			}
		}
		for _, r := range d.m.Routes {
			if r.Stack == name && r.Via != "" && r.To != "" && in[r.Via] && in[r.To] {
				d.p("  Rel(%s, %s, %s)\n", mid("c", r.Via), mid("c", r.To), q(strings.Join(r.Sites, ", ")+" "+r.Match))
			}
		}
		for _, p := range d.m.Parties {
			for _, sv := range uniq(append([]string(nil), p.Services...)) {
				if stackOf(sv) == id && in[sv] {
					d.p("  Rel(%s, %s, %s)\n", mid("c", sv), mid("p", p.ID), q("uses"))
				}
			}
		}
		d.p("```\n\n")
		d.p("| Container | Kind | Code | Size | Evidence |\n|---|---|---|---|---|\n")
		for _, f := range boxes {
			code, size := "", ""
			from := []string{f.Key}
			if l := d.link(f.Key); l != nil {
				code = strings.Join(l.Sources, ", ")
				if l.Narrowing.State == "narrowed" {
					code += " (narrowed to " + strings.Join(l.Narrowed, ", ")
					if len(l.Excluded) > 0 {
						code += "; excluded " + strings.Join(l.Excluded, ", ")
					}
					code += ")"
				}
				from = append(from, l.From...)
			} else if im := d.image(f.Key); im != nil {
				code = "third-party image " + im.ImageRepo
			}
			if sm := d.service(f.Key); sm != nil && sm.Size.Files > 0 {
				size = plural(sm.Size.Lines, "line", "lines") + " (" + langs(sm.Size) + ")" + tests(sm.Size)
			}
			kind := "service"
			if f.Kind == fact.KindDatastore {
				kind = "data store, " + f.Str("engine")
			}
			d.p("| %s | %s | %s | %s | %s |\n", cell(f.Str("name")), cell(kind), cell(code), cell(size), d.cite(from...))
		}
		d.p("\n")
		for _, f := range boxes {
			d.endpoints(f)
		}
	}
	if len(d.m.CIImages) > 0 {
		d.p("### Images built in CI that no stack runs\n\n| Image | Dockerfile | Pushed to | Evidence |\n|---|---|---|---|\n")
		for _, c := range d.m.CIImages {
			var to []string
			for _, p := range c.Pushes {
				to = append(to, p.Target)
			}
			push := strings.Join(uniq(to), ", ")
			if push == "" {
				push = "no push seen"
			}
			d.p("| %s | %s | %s | %s |\n", cell(strings.Join(c.ImageRepos, ", ")), cell(c.Dockerfile+" "+c.Target), cell(push), d.cite(c.From...))
		}
		d.p("\n")
	}
	d.moduleGraphs()
}

// endpointNote is the endpoint count in a container's description, or "" when
// the service has none. The count includes rows on broad links.
func (d *doc) endpointNote(key string) string {
	sm := d.service(key)
	if sm == nil || sm.Endpoints == nil || sm.Endpoints.Total == 0 {
		return ""
	}
	e := sm.Endpoints
	return fmt.Sprintf("%s: %d required, %d anonymous, %d unknown", plural(e.Total, "endpoint", "endpoints"), e.Required, e.Anonymous, e.Unknown)
}

// endpoints is the endpoints table of one service: method, path, auth and the
// routes that reach it (only the edges to this service: the same route key
// can reach other services from other stacks). A row on a broad link (the link keeps more than one
// app) is marked, because the endpoint may belong to another app.
func (d *doc) endpoints(f fact.Fact) {
	var rows []rules.EndpointRow
	for _, r := range d.m.Endpoints {
		if r.Service == f.Key {
			rows = append(rows, r)
		}
	}
	if len(rows) == 0 {
		return
	}
	d.p("Endpoints of %s:\n\n| Method | Path | Auth | Routes | Evidence |\n|---|---|---|---|---|\n", md(f.Str("name")))
	for _, r := range rows {
		auth := r.Auth.State
		if len(r.Auth.Markers) > 0 {
			auth += " (" + strings.Join(r.Auth.Markers, ", ") + ")"
		}
		path := r.Path
		if r.Link == "broad" {
			path += " (broad link: the endpoint may belong to another app)"
		}
		var via []string
		for _, key := range r.Routes {
			for _, e := range d.m.Routes {
				if e.Route == key && e.To == r.Service {
					via = append(via, strings.Join(e.Sites, ", ")+" "+e.Match)
				}
			}
		}
		routes := strings.Join(via, "; ")
		if r.Public {
			routes += " (public)"
		}
		d.p("| %s | %s | %s | %s | %s |\n", cell(r.Method), cell(path), cell(auth), cell(strings.TrimSpace(routes)), d.cite(r.From...))
	}
	d.p("\n")
}

// moduleGraphs draws each service's own packages and their imports (Go).
func (d *doc) moduleGraphs() {
	g := d.m.Modules
	if g == nil || len(g.Services) == 0 {
		return
	}
	d.p("### Module graphs\n\nThe repo's own packages each service reaches, and the imports between them. ")
	d.p("Read from the import declarations; Go only for now.\n\n")
	// Services with the same packages share one graph.
	type group struct {
		services []string
		sm       rules.ServiceModules
	}
	var groups []*group
	byPkgs := map[string]*group{}
	for _, sm := range g.Services {
		k := sm.Reach + "|" + strings.Join(sm.Packages, ",")
		if gr := byPkgs[k]; gr != nil {
			gr.services = append(gr.services, sm.Service)
			continue
		}
		gr := &group{services: []string{sm.Service}, sm: sm}
		byPkgs[k] = gr
		groups = append(groups, gr)
	}
	pk := map[string]rules.Package{}
	for _, p := range g.Packages {
		pk[p.Package] = p
	}
	for _, gr := range groups {
		in := map[string]bool{}
		for _, p := range gr.sm.Packages {
			in[p] = true
		}
		var facts []string
		var edges []rules.ImportEdge
		for _, e := range g.Edges {
			if in[e.From] && in[e.To] {
				edges = append(edges, e)
				facts = append(facts, e.Facts...)
			}
		}
		how := "every package in its sources"
		if gr.sm.Reach == "entrypoints" {
			how = "followed from " + strings.Join(gr.sm.Roots, ", ")
		}
		d.p("**%s**: %s, %s; %s %s\n\n", md(d.names(gr.services)), plural(len(gr.sm.Packages), "package", "packages"), plural(len(edges), "import", "imports"), md(how), d.cite(facts...))
		trim := commonPrefix(gr.sm.Packages)
		d.p("```mermaid\nflowchart LR\n")
		for _, p := range gr.sm.Packages {
			label := strings.TrimPrefix(p, trim)
			if label == "" {
				label = p
			}
			d.p("  %s[%s]\n", mid("m", p), q(label))
		}
		for _, e := range edges {
			d.p("  %s --> %s\n", mid("m", e.From), mid("m", e.To))
		}
		d.p("```\n\n")
		d.p("| Package | Imported by | Imports | Depth |\n|---|---|---|---|\n")
		for _, p := range gr.sm.Packages {
			x := pk[p]
			name := codeCell(p)
			if x.Cycle {
				name += " (in a cycle)"
			}
			d.p("| %s | %d | %d | %d |\n", name, x.FanIn, x.FanOut, x.Depth)
		}
		d.p("\n")
	}
	if len(g.Cycles) > 0 {
		d.p("Import cycles:\n\n")
		for _, c := range g.Cycles {
			var ps []string
			for _, p := range c.Packages {
				ps = append(ps, code(p))
			}
			d.p("- %s %s\n", strings.Join(ps, " ⇄ "), d.cite(c.From...))
		}
		d.p("\n")
	}
}

func (d *doc) deployment() {
	d.p("## 7. Deployment view\n\n")
	if len(d.m.Stacks) == 0 {
		d.p("No deployment stack is described in the repository.\n\n")
		return
	}
	d.p("Production is a stack a CI job on the default branch (%s) starts, or one a person declared or confirmed.\n\n", code(d.m.Settings.DefaultBranch))
	d.p("| Stack | Role | Why | Evidence |\n|---|---|---|---|\n")
	for _, st := range d.m.Stacks {
		why := []string{}
		for _, r := range st.Reasons {
			why = append(why, r.Workflow+" job "+r.Job+": "+r.Detail)
		}
		if st.Declared != nil {
			why = append(why, "declared by "+st.Declared.By)
		}
		if st.Confirmed != nil {
			why = append(why, "confirmed by a person")
		}
		if len(why) == 0 {
			why = append(why, "no CI job starts it")
		}
		d.p("| %s | %s | %s | %s |\n", cell(d.keyLabel(st.Stack)), cell(string(st.Role)), cell(strings.Join(why, "; ")), d.cite(st.Stack))
	}
	d.p("\n")
}

func (d *doc) crosscutting() {
	d.p("## 8. Crosscutting concepts\n\n### Data\n\n")
	var stores []fact.Fact
	for _, f := range d.s.Facts {
		if f.Kind == fact.KindDatastore {
			stores = append(stores, f)
		}
	}
	if len(stores) == 0 {
		d.p("No data store runs in a stack of the repository.\n\n")
	} else {
		d.p("| Data store | Engine | Stack | Evidence |\n|---|---|---|---|\n")
		for _, f := range stores {
			d.p("| %s | %s | %s | %s |\n", cell(f.Str("name")), cell(strings.TrimSpace(f.Str("engine")+" "+f.Str("version"))), cell(d.label(f.Str("stack"))), d.cite(f.Key))
		}
		d.p("\n")
	}
	if len(d.m.Tables) > 0 {
		check := 0
		for _, t := range d.m.Tables {
			check += len(t.Check)
		}
		d.p("%s in the schema sources, %s whose names look sensitive.\n\n", plural(len(d.m.Tables), "table", "tables"), plural(check, "column", "columns"))
		if check > 0 {
			d.p("| Table | Columns to check | Evidence |\n|---|---|---|\n")
			for _, t := range d.m.Tables {
				if len(t.Check) == 0 {
					continue
				}
				var cols, from []string
				for _, c := range t.Check {
					cols = append(cols, c.Column)
					from = append(from, c.From...)
				}
				d.p("| %s | %s | %s |\n", cell(t.Table), cell(strings.Join(cols, ", ")), d.cite(from...))
			}
			d.p("\n")
		}
	}
	if len(d.m.AITools) > 0 {
		d.p("### AI coding tools\n\nThe repository is set up for: ")
		var ts []string
		for _, a := range d.m.AITools {
			ts = append(ts, md(a.Name)+" "+d.cite(a.From...))
		}
		d.p("%s.\n\n", strings.Join(ts, ", "))
	}
}

func (d *doc) risks() {
	d.p("## 11. Risks and technical debt\n\n")
	if len(d.m.Findings) == 0 {
		d.p("The rules found nothing to act on or confirm.\n\n")
		return
	}
	by := map[string][]rules.Finding{}
	var order []string
	for _, f := range d.m.Findings {
		if by[f.Rule] == nil {
			order = append(order, f.Rule)
		}
		by[f.Rule] = append(by[f.Rule], f)
	}
	for _, r := range order {
		w, ok := d.o.Words[r]
		title := r
		if ok && w.Title != "" {
			title = w.Title
		}
		d.p("### %s (%d)\n\n", md(title), len(by[r]))
		if ok && w.Meaning != "" {
			d.p("%s\n\n", w.Meaning)
		}
		if ok && w.Action != "" {
			d.p("What to do: %s\n\n", w.Action)
		}
		for _, f := range by[r] {
			d.p("- %s: %s %s\n", md(d.name(f.Subject)), md(f.Detail), d.cite(f.From...))
		}
		d.p("\n")
	}
}

