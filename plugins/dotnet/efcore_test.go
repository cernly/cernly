func TestEFPositional(t *testing.T) {
	up := `            const string Schema = "sales";
            migrationBuilder.EnsureSchema(Schema);
            migrationBuilder.CreateTable("Items", table => new
                {
                    Id = table.Column<long>("bigint", null, null, false, "item_id", false),
                    Code = table.Column<string>(maxLength: 32, nullable: true)
                }, Schema, table => { table.PrimaryKey("PK_Items", x => new { x.Id }); });
            migrationBuilder.RenameColumn("Code", "Items", "Sku", Schema);`
	files := map[string]string{
		"src/Infrastructure/Infrastructure.csproj":          efProject("Npgsql.EntityFrameworkCore.PostgreSQL"),
		"src/Infrastructure/Migrations/1_Items.cs":          migration("Items", up),
		"src/Infrastructure/Migrations/1_Items.Designer.cs": designer("Items", "1_Items", "AppDbContext"),
	}
	res := efRun(t, files)
	cols := byKey(res.Facts, fact.KindDBColumn)
	id, ok := cols[efColPrefix+"sales.Items.item_id"]
	if !ok {
		t.Fatalf("columns: %v (errors %v)", cols, res.Errors)
	}
	if id.Attrs["native_type"] != "bigint" || id.Attrs["type"] != "long" || id.Attrs["primary_key"] != true || id.Attrs["nullable"] != false {
		t.Errorf("item_id: %v", id.Attrs)
	}
	sku, ok := cols[efColPrefix+"sales.Items.Sku"]
	if !ok {
		t.Fatalf("columns: %v", cols)
	}
	if sku.Attrs["native_type"] != nil || sku.Attrs["nullable"] != true || sku.Attrs["ext"].(map[string]any)["max_length"] != 32 {
		t.Errorf("Sku: %v", sku.Attrs)
	}
}

func TestEFProvider(t *testing.T) {
	application := `<Project Sdk="Microsoft.NET.Sdk">
  <ItemGroup>
    <ProjectReference Include="..\Application\Application.csproj" />
  </ItemGroup>
</Project>
`
	t.Run("referenced", func(t *testing.T) {
		// Infrastructure -> Application, which holds the provider; Application
		// refers back (a cycle).
		files := efRepo(t, nil, map[string]string{
			"src/Infrastructure/Infrastructure.csproj": application,
			"src/Application/Application.csproj": `<Project Sdk="Microsoft.NET.Sdk">
  <ItemGroup>
    <PackageReference Include="microsoft.entityframeworkcore.sqlserver" Version="8.0.10" />
    <ProjectReference Include="..\Infrastructure\Infrastructure.csproj" />
  </ItemGroup>
</Project>
`,
		})
		got := byKey(efRun(t, files).Facts, fact.KindDBTable)
		f, ok := got[efPrefix+"dbo.PurchaseOrders"]
		if !ok {
			t.Fatalf("tables: %v", got)
		}
		if at, _ := f.Attrs["ext"].(map[string]any)["provider_at"].(string); !strings.HasPrefix(at, "src/Application/Application.csproj:") {
			t.Errorf("provider_at: %v", f.Attrs["ext"])
		}
	})
	t.Run("npgsql", func(t *testing.T) {
		got := byKey(efRun(t, efRepo(t, []string{"Npgsql.EntityFrameworkCore.PostgreSQL"}, nil)).Facts, fact.KindDBTable)
		f, ok := got[efPrefix+"public.PurchaseOrders"]
		if !ok || f.Attrs["ext"].(map[string]any)["provider"] != "postgresql" {
			t.Errorf("tables: %v", got)
		}
	})
	for name, pkgs := range map[string][]string{
		"none": nil,
		"both": {"Microsoft.EntityFrameworkCore.SqlServer", "Npgsql.EntityFrameworkCore.PostgreSQL"},
	} {
		t.Run(name, func(t *testing.T) {
			res := efRun(t, efRepo(t, pkgs, nil))
			got := byKey(res.Facts, fact.KindDBTable)
			f, ok := got[efPrefix+"PurchaseOrders"]
			if !ok || len(got) != 1 {
				t.Fatalf("tables: %v", got)
			}
			ext := f.Attrs["ext"].(map[string]any)
			if f.Attrs["name"] != "PurchaseOrders" || ext["provider_unknown"] != true || ext["provider"] != nil {
				t.Errorf("table: %v", f.Attrs)
			}
			col := byKey(res.Facts, fact.KindDBColumn)[efColPrefix+"PurchaseOrders.Total"]
			if col.Attrs["table"] != "PurchaseOrders" || col.Attrs["ext"].(map[string]any)["provider_unknown"] != true {
				t.Errorf("column: %v", col.Attrs)
			}
		})
	}
}

func TestEFSql(t *testing.T) {
	up := `            migrationBuilder.Sql("CREATE TABLE audit (id int)");
            var sqlVar = "CREATE TABLE hidden (id int)";
            migrationBuilder.Sql(sqlVar);`
	files := efRepo(t, []string{"Microsoft.EntityFrameworkCore.SqlServer"}, map[string]string{
		"src/Infrastructure/Migrations/20240301_Audit.cs":          migration("Audit", up),
		"src/Infrastructure/Migrations/20240301_Audit.Designer.cs": designer("Audit", "20240301_Audit", "AppDbContext"),
	})
	res := efRun(t, files)
	tables := byKey(res.Facts, fact.KindDBTable)
	audit, ok := tables[efPrefix+"dbo.audit"]
	if !ok {
		t.Fatalf("tables: %v (errors %v)", tables, res.Errors)
	}
	src := migration("Audit", up)
	path := "src/Infrastructure/Migrations/20240301_Audit.cs"
	if audit.Evidence[0].Path != path || audit.Evidence[0].Line != lineOf(t, src, `Sql("CREATE`) {
		t.Errorf("audit evidence: %v", audit.Evidence)
	}
	col := byKey(res.Facts, fact.KindDBColumn)[efColPrefix+"dbo.audit.id"]
	if col.Attrs["type"] != "int" {
		t.Errorf("audit.id: %v", col.Attrs)
	}
	for k := range tables {
		if strings.Contains(k, "hidden") {
			t.Errorf("non-literal Sql replayed: %s", k)
		}
	}
	for _, f := range tables {
		ext := f.Attrs["ext"].(map[string]any)
		at := path + ":" + strconv.Itoa(lineOf(t, src, "Sql(sqlVar)"))
		if ext["unread_operations"] != 1 || len(ext["unread_at"].([]any)) != 1 || ext["unread_at"].([]any)[0] != at {
			t.Errorf("%s ext: %v, want unread at %s", f.Key, ext, at)
		}
	}
}

// T-SQL in migrationBuilder.Sql against the tables EF built: [bracketed]
// names, any case. A statement that names a table the set does not hold
// changes nothing and counts as unread.
func TestEFSqlServerSql(t *testing.T) {
	up := `            migrationBuilder.Sql("ALTER TABLE [dbo].[PurchaseOrders] ADD [Note] nvarchar(max) NULL");
            migrationBuilder.Sql("ALTER TABLE purchaseorders ADD Note2 int NULL");
            migrationBuilder.Sql("CREATE TABLE [dbo].[Audit] ([Id] int NOT NULL)");
            migrationBuilder.Sql("ALTER TABLE Nowhere ADD X int NULL");`
	files := efRepo(t, []string{"Microsoft.EntityFrameworkCore.SqlServer"}, map[string]string{
		"src/Infrastructure/Migrations/20240301_Tsql.cs":          migration("Tsql", up),
		"src/Infrastructure/Migrations/20240301_Tsql.Designer.cs": designer("Tsql", "20240301_Tsql", "AppDbContext"),
	})
	res := efRun(t, files)
	if len(res.Errors) != 0 {
		t.Fatalf("errors: %v", res.Errors)
	}
	cols := byKey(res.Facts, fact.KindDBColumn)
	for _, k := range []string{"dbo.PurchaseOrders.Note", "dbo.PurchaseOrders.Note2", "dbo.Audit.Id"} {
		if _, ok := cols[efColPrefix+k]; !ok {
			t.Errorf("no column %s: %v", k, cols)
		}
	}
	src := migration("Tsql", up)
	at := "src/Infrastructure/Migrations/20240301_Tsql.cs:" + strconv.Itoa(lineOf(t, src, "Nowhere"))
	for _, f := range byKey(res.Facts, fact.KindDBTable) {
		ext := f.Attrs["ext"].(map[string]any)
		if ext["unread_operations"] != 1 || ext["unread_at"].([]any)[0] != at {
			t.Errorf("%s ext: %v, want one unread at %s", f.Key, ext, at)
		}
	}
}

