func efProject(pkgs ...string) string {
	var b strings.Builder
	b.WriteString("<Project Sdk=\"Microsoft.NET.Sdk\">\n  <ItemGroup>\n")
	for _, p := range pkgs {
		b.WriteString(`    <PackageReference Include="` + p + `" Version="8.0.10" />` + "\n")
	}
	b.WriteString("  </ItemGroup>\n</Project>\n")
	return b.String()
}

// designer is the generated partial that carries the migration's id and
// context, with model code that must never be replayed.
func designer(class, id, context string) string {
	return `// <auto-generated />
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;

namespace Shop.Infrastructure.Migrations
{
    [DbContext(typeof(` + context + `))]
    [Migration("` + id + `")]
    partial class ` + class + `
    {
        protected override void BuildTargetModel(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity("Shop.Ghost", b =>
                {
                    b.Property<int>("Id").HasColumnType("int");
                    b.ToTable("Ghost");
                });
        }
    }
}
`
}

func migration(class, up string) string {
	return `using Microsoft.EntityFrameworkCore.Migrations;

namespace Shop.Infrastructure.Migrations
{
    public partial class ` + class + ` : Migration
    {
        protected override void Up(MigrationBuilder migrationBuilder)
        {
` + up + `
        }

        protected override void Down(MigrationBuilder migrationBuilder)
        {
            migrationBuilder.DropTable(name: "Everything");
        }
    }
}
`
}

const initUp = `            migrationBuilder.CreateTable(
                name: "Orders",
                columns: table => new
                {
                    Id = table.Column<int>(type: "int", nullable: false)
                        .Annotation("SqlServer:Identity", "1, 1"),
                    Note = table.Column<string>(type: "nvarchar(max)", nullable: true)
                },
                constraints: table =>
                {
                    table.PrimaryKey("PK_Orders", x => x.Id);
                });`

const renameUp = `            migrationBuilder.DropPrimaryKey(
                name: "PK_Orders",
                table: "Orders");

            migrationBuilder.RenameTable(
                name: "Orders",
                newName: "PurchaseOrders");

            migrationBuilder.AddColumn<decimal>(
                name: "Total",
                table: "PurchaseOrders",
                type: "decimal(18,2)",
                nullable: false,
                defaultValue: 0m);

            migrationBuilder.DropColumn(
                name: "Note",
                table: "PurchaseOrders");

            migrationBuilder.AddPrimaryKey(
                name: "PK_PurchaseOrders",
                table: "PurchaseOrders",
                column: "Id");`

// efRepo is an Infrastructure project with the provider package (when given)
// and the two migrations of TestEFReplay, plus the files passed in.
func efRepo(t *testing.T, pkgs []string, extra map[string]string) map[string]string {
	t.Helper()
	files := map[string]string{
		"src/Infrastructure/Infrastructure.csproj":                   efProject(pkgs...),
		"src/Infrastructure/Migrations/20240101_Init.cs":             migration("Init", initUp),
		"src/Infrastructure/Migrations/20240101_Init.Designer.cs":    designer("Init", "20240101_Init", "AppDbContext"),
		"src/Infrastructure/Migrations/20240201_Rename.cs":           migration("Rename", renameUp),
		"src/Infrastructure/Migrations/20240201_Rename.Designer.cs":  designer("Rename", "20240201_Rename", "AppDbContext"),
		"src/Infrastructure/Migrations/AppDbContextModelSnapshot.cs": snapshot,
	}
	for k, v := range extra {
		files[k] = v
	}
	return files
}

const snapshot = `// <auto-generated />
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;

namespace Shop.Infrastructure.Migrations
{
    [DbContext(typeof(AppDbContext))]
    partial class AppDbContextModelSnapshot : ModelSnapshot
    {
        protected override void BuildModel(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity("Shop.PurchaseOrder", b =>
                {
                    b.Property<int>("Id").HasColumnType("int");
                    b.HasKey("Id");
                    b.ToTable("PurchaseOrders");
                });
            modelBuilder.Entity("Shop.Ghost", b =>
                {
                    b.ToTable("Ghost");
                });
        }
    }
}
`

const efPrefix = "db_table:efcore:src/Infrastructure/Migrations:AppDbContext:"
const efColPrefix = "db_column:efcore:src/Infrastructure/Migrations:AppDbContext:"

func lineOf(t *testing.T, src, sub string) int {
	t.Helper()
	i := strings.Index(src, sub)
	if i < 0 {
		t.Fatalf("%q not in source", sub)
	}
	return strings.Count(src[:i], "\n") + 1
}

func efRun(t *testing.T, files map[string]string) plugin.Result {
	t.Helper()
	return Plugin{}.Run(repotest.Files(t, files))
}

func TestEFReplay(t *testing.T) {
	res := efRun(t, efRepo(t, []string{"Microsoft.EntityFrameworkCore.SqlServer"}, nil))
	if len(res.Errors) != 0 {
		t.Fatalf("errors: %v", res.Errors)
	}
	tables := byKey(res.Facts, fact.KindDBTable)
	if len(tables) != 1 {
		t.Fatalf("tables: %v", tables)
	}
	tb, ok := tables[efPrefix+"dbo.PurchaseOrders"]
	if !ok {
		t.Fatalf("no dbo.PurchaseOrders: %v", tables)
	}
	if tb.Attrs["name"] != "dbo.PurchaseOrders" || tb.Plugin != "dotnet" {
		t.Errorf("table: %+v", tb)
	}
	ext := tb.Attrs["ext"].(map[string]any)
	if ext["context"] != "AppDbContext" || ext["provider"] != "sqlserver" || ext["provider_unknown"] != nil || ext["unread_operations"] != nil {
		t.Errorf("table ext: %v", ext)
	}
	cols := byKey(res.Facts, fact.KindDBColumn)
	if len(cols) != 2 {
		t.Fatalf("columns: %v", cols)
	}
	id, ok := cols[efColPrefix+"dbo.PurchaseOrders.Id"]
	if !ok {
		t.Fatalf("no Id: %v", cols)
	}
	if id.Attrs["table"] != "dbo.PurchaseOrders" || id.Attrs["name"] != "Id" || id.Attrs["type"] != "int" ||
		id.Attrs["native_type"] != "int" || id.Attrs["nullable"] != false || id.Attrs["primary_key"] != true {
		t.Errorf("Id: %v", id.Attrs)
	}
	total, ok := cols[efColPrefix+"dbo.PurchaseOrders.Total"]
	if !ok {
		t.Fatalf("no Total: %v", cols)
	}
	if total.Attrs["type"] != "decimal" || total.Attrs["native_type"] != "decimal(18,2)" || total.Attrs["nullable"] != false || total.Attrs["primary_key"] != nil {
		t.Errorf("Total: %v", total.Attrs)
	}
	src := migration("Rename", renameUp)
	want := fact.Evidence{Path: "src/Infrastructure/Migrations/20240201_Rename.cs", Line: lineOf(t, src, "migrationBuilder.AddColumn"), Unit: "src/Infrastructure"}
	if len(total.Evidence) != 1 || total.Evidence[0] != want {
		t.Errorf("Total evidence: %v, want %v", total.Evidence, want)
	}
}

// Review Focus 4: the model snapshot and the .Designer.cs model code are not
// migrations; the Designer only names the id and the context.
func TestEFSnapshotIgnored(t *testing.T) {
	res := efRun(t, efRepo(t, []string{"Microsoft.EntityFrameworkCore.SqlServer"}, nil))
	for k := range byKey(res.Facts, fact.KindDBTable) {
		if strings.Contains(k, "Ghost") || strings.Contains(k, "Shop.") {
			t.Errorf("model code replayed: %s", k)
		}
	}
	// Only the snapshot and the Designer files: no migrations, no tables.
	only := efRun(t, map[string]string{
		"src/Infrastructure/Infrastructure.csproj":                   efProject("Microsoft.EntityFrameworkCore.SqlServer"),
		"src/Infrastructure/Migrations/20240101_Init.Designer.cs":    designer("Init", "20240101_Init", "AppDbContext"),
		"src/Infrastructure/Migrations/AppDbContextModelSnapshot.cs": snapshot,
	})
	if n := len(byKey(only.Facts, fact.KindDBTable)); n != 0 || len(only.Errors) != 0 {
		t.Errorf("snapshot and designer gave %d tables, errors %v", n, only.Errors)
	}
	// The context comes from [DbContext(typeof(...))] in the Designer.
	other := efRepo(t, []string{"Microsoft.EntityFrameworkCore.SqlServer"}, map[string]string{
		"src/Infrastructure/Migrations/20240101_Init.Designer.cs":   designer("Init", "20240101_Init", "ShopContext"),
		"src/Infrastructure/Migrations/20240201_Rename.Designer.cs": designer("Rename", "20240201_Rename", "ShopContext"),
	})
	got := byKey(efRun(t, other).Facts, fact.KindDBTable)
	if _, ok := got["db_table:efcore:src/Infrastructure/Migrations:ShopContext:dbo.PurchaseOrders"]; !ok || len(got) != 1 {
		t.Errorf("context from Designer: %v", got)
	}
}

