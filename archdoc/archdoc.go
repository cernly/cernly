// keyLabel is label for a stack:<tool>:<name> key, with the tool added
// when a stack of another tool has the same name: "chart (helm)".
func (d *doc) keyLabel(key string) string {
	name, tool := stackName(key), ""
	if p := strings.SplitN(key, ":", 3); len(p) == 3 {
		tool = p[1]
	}
	for _, st := range d.m.Stacks {
		if st.Stack != key && stackName(st.Stack) == name {
			return d.label(name) + " (" + tool + ")"
		}
	}
	return d.label(name)
}

func (d *doc) label(stack string) string {
	if l := d.o.Labels[stack]; l != "" {
		return l
	}
	return stack
}

// name is a subject as a reader reads it: "api (stack prod)".
func (d *doc) name(key string) string {
	parts := strings.Split(key, ":")
	switch {
	case (parts[0] == "service" || parts[0] == "datastore") && len(parts) == 4:
		return parts[3] + " (stack " + d.label(parts[2]) + ")"
	case parts[0] == "ci_image":
		return strings.Join(parts[1:], " ") + " (built in CI)"
	case parts[0] == "stack" && len(parts) == 3:
		return "stack " + d.label(parts[2])
	case parts[0] == "image_recipe" && len(parts) == 3:
		if parts[2] == "_final" {
			return parts[1] + ", final stage"
		}
		return parts[1] + ", stage " + parts[2]
	}
	return key
}

func (d *doc) names(keys []string) string {
	var out []string
	for _, k := range uniq(append([]string(nil), keys...)) {
		out = append(out, d.name(k))
	}
	if len(out) == 0 {
		return "none"
	}
	return strings.Join(out, ", ")
}

